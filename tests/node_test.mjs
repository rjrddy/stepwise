import assert from 'node:assert/strict';
import {Client,Tape,redact} from '../sdk/node/index.mjs';
const base=process.env.STEPWISE_BASE;
const secret='SYNTHETIC-NEVER-PERSIST-KEY';
const client=new Client(base,{token:process.env.STEPWISE_TOKEN,secrets:[secret]});
const {id,tape}=await client.record('Node synthetic model and tool');
await tape.call('model','plan',{message:'safe',api_key:secret}, async()=>({text:'lookup',nonce:Math.random()}));
await tape.call('tool','lookup',{sku:'SYNTH'},async()=>({result:42,explanation:secret}));
const replay=await client.replay(id);
await replay.call('model','plan',{message:'safe',api_key:secret},()=>assert.fail('provider called'));
await replay.call('tool','lookup',{sku:'SYNTH'},()=>assert.fail('tool called'));
replay.finish();assert.deepEqual(replay.events,tape.events);
await assert.rejects(()=>replay.call('tool','extra',{},()=>1),/divergence/);
const failing=new Tape();await assert.rejects(()=>failing.call('tool','fail',{},async()=>{throw Error('seeded failure')}));
const failureReplay=new Tape({replay:failing.events});
await assert.rejects(()=>failureReplay.call('tool','fail',{},()=>assert.fail()),/seeded failure/);
assert.equal(JSON.stringify(redact({password:secret,q:secret},[secret])).includes(secret),false);
let unblock;const slow=new Tape();const pending=slow.call('tool','slow',{},()=>new Promise(r=>{unblock=r}));
await assert.rejects(()=>slow.call('tool','race',{},()=>1),/concurrent/);unblock(1);await pending;
console.log(JSON.stringify({node_sdk:'pass',run_id:id,exact_frames:replay.events.length,secret_absent:!JSON.stringify(tape.events).includes(secret)}));
